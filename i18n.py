_language = "it"


def detect_system_language() -> str:
    language, _encoding = locale.getlocale()
    raw = (language or "").lower()
    code = raw.split("_")[0]
    if code not in LANGUAGES and raw[:2] in LANGUAGES:
        code = raw[:2]
    return code if code in LANGUAGES else "en"


def set_language(language: str) -> None:
    if language not in LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")
    global _language
    _language = language


def get_language() -> str:
    return _language


def tr(key: str, **values) -> str:
    catalog = TRANSLATIONS.get(_language, TRANSLATIONS["en"])
    template = catalog.get(key, TRANSLATIONS["en"].get(key, key))
    return template.format(**values) if values else template


def trn(key: str, count: int, **values) -> str:
    suffix = "one" if count == 1 else "other"
    return tr(f"{key}.{suffix}", count=count, **values)
